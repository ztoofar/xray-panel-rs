use anyhow::{bail, Context, Result};
use base64::{
    engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD},
    Engine as _,
};
use serde_json::{json, Map, Value};

use crate::db::models::{Client, Inbound};

pub fn client_link(inbound: &Inbound, client: &Client, address: &str) -> Result<Option<String>> {
    if !client.enable {
        return Ok(None);
    }
    let remark = if inbound.remark.is_empty() {
        client.email.clone()
    } else {
        format!("{}-{}", inbound.remark, client.email)
    };
    let stream = &inbound.stream_settings.0;
    let network = get(stream, &["network"]).unwrap_or("tcp");
    let security = get(stream, &["security"]).unwrap_or("none");
    let host = host_of(stream, network);
    let path = path_of(stream, network);
    let sni = get(stream, &["tlsSettings", "serverName"])
        .or_else(|| get(stream, &["realitySettings", "serverName"]))
        .unwrap_or_default();
    let fingerprint = get(stream, &["tlsSettings", "settings", "fingerprint"])
        .or_else(|| get(stream, &["realitySettings", "settings", "fingerprint"]))
        .unwrap_or_default();
    let alpn = alpn_of(stream);
    let header_type = if network == "tcp" {
        get(stream, &["tcpSettings", "header", "type"]).unwrap_or("none")
    } else {
        "none"
    };
    let authority = authority(address, inbound.port);
    let creds = client
        .settings
        .0
        .as_object()
        .with_context(|| format!("client {}: settings must be an object", client.id))?;

    let link = match inbound.protocol.as_str() {
        "vless" => {
            let id = credential(creds, "id", &client.email)?;
            let flow = creds
                .get("flow")
                .and_then(Value::as_str)
                .unwrap_or_default();
            // VLESS encryption: settings.encryption is the client-side value
            // generated by xray vlessenc; settings.decryption stays server-side.
            let encryption = inbound
                .settings
                .0
                .get("encryption")
                .and_then(Value::as_str)
                .filter(|value| !value.is_empty())
                .unwrap_or("none");
            let mut params = vec![
                ("encryption", encryption.to_string()),
                ("type", network.to_string()),
                ("security", security.to_string()),
            ];
            push_transport(&mut params, network, host, path, header_type);
            if security == "tls" || security == "reality" {
                push_tls(&mut params, sni, fingerprint, &alpn);
            }
            if security == "reality" {
                push_reality(stream, &mut params);
            }
            if !flow.is_empty() && !inbound.disable_flow {
                params.push(("flow", flow.to_string()));
            }
            format!(
                "vless://{id}@{authority}?{}#{}",
                query(&params),
                encode(&remark)
            )
        }
        "vmess" => {
            let id = credential(creds, "id", &client.email)?;
            let mut map = Map::new();
            map.insert("v".into(), json!("2"));
            map.insert("ps".into(), json!(remark));
            map.insert("add".into(), json!(address));
            map.insert("port".into(), json!(inbound.port.to_string()));
            map.insert("id".into(), json!(id));
            map.insert("aid".into(), json!("0"));
            map.insert("scy".into(), json!("auto"));
            map.insert("net".into(), json!(network));
            map.insert("type".into(), json!(header_type));
            map.insert("host".into(), json!(host));
            map.insert("path".into(), json!(path));
            map.insert(
                "tls".into(),
                json!(if security == "tls" || security == "reality" {
                    "tls"
                } else {
                    ""
                }),
            );
            map.insert("sni".into(), json!(sni));
            map.insert("alpn".into(), json!(alpn));
            map.insert("fp".into(), json!(fingerprint));
            let payload = serde_json::to_vec(&map).context("编码 VMess 链接失败")?;
            format!("vmess://{}", STANDARD.encode(payload))
        }
        "trojan" => {
            let password = credential(creds, "password", &client.email)?;
            let mut params = vec![
                ("type", network.to_string()),
                (
                    "security",
                    if security == "none" { "none" } else { "tls" }.to_string(),
                ),
            ];
            push_transport(&mut params, network, host, path, header_type);
            if security != "none" {
                push_tls(&mut params, sni, fingerprint, &alpn);
            }
            format!(
                "trojan://{password}@{authority}?{}#{}",
                query(&params),
                encode(&remark)
            )
        }
        "shadowsocks" => {
            let method = get(&inbound.settings.0, &["method"]).unwrap_or("2022-blake3-aes-128-gcm");
            let password = credential(creds, "password", &client.email)?;
            let userinfo = URL_SAFE_NO_PAD.encode(format!("{method}:{password}"));
            format!("ss://{userinfo}@{authority}#{}", encode(&remark))
        }
        "http" | "mixed" => return Ok(None),
        other => bail!("分享链接不支持该协议：{other}"),
    };

    Ok(Some(link))
}

fn credential(creds: &Map<String, Value>, key: &str, email: &str) -> Result<String> {
    creds
        .get(key)
        .and_then(Value::as_str)
        .filter(|value| !value.is_empty())
        .map(str::to_string)
        .with_context(|| format!("客户端 {email}：缺少凭据 \"{key}\""))
}

fn get<'a>(value: &'a Value, path: &[&str]) -> Option<&'a str> {
    let mut current = value;
    for key in path {
        current = current.get(*key)?;
    }
    current.as_str()
}

fn host_of<'a>(stream: &'a Value, network: &str) -> &'a str {
    match network {
        "ws" => stream
            .pointer("/wsSettings/headers/Host")
            .and_then(Value::as_str)
            .unwrap_or_default(),
        "grpc" => get(stream, &["grpcSettings", "authority"]).unwrap_or_default(),
        "http" | "h2" => stream
            .pointer("/httpSettings/host")
            .and_then(Value::as_array)
            .and_then(|hosts| hosts.iter().find_map(Value::as_str))
            .unwrap_or_default(),
        "xhttp" => get(stream, &["xhttpSettings", "host"]).unwrap_or_default(),
        "tcp" => stream
            .pointer("/tcpSettings/header/request/headers/Host")
            .and_then(Value::as_array)
            .and_then(|hosts| hosts.iter().find_map(Value::as_str))
            .unwrap_or_default(),
        _ => "",
    }
}

fn path_of<'a>(stream: &'a Value, network: &str) -> &'a str {
    match network {
        "ws" => get(stream, &["wsSettings", "path"]).unwrap_or_default(),
        "grpc" => get(stream, &["grpcSettings", "serviceName"]).unwrap_or_default(),
        "http" | "h2" => get(stream, &["httpSettings", "path"]).unwrap_or_default(),
        "xhttp" => get(stream, &["xhttpSettings", "path"]).unwrap_or_default(),
        "tcp" => stream
            .pointer("/tcpSettings/header/request/path")
            .and_then(Value::as_array)
            .and_then(|paths| paths.iter().find_map(Value::as_str))
            .unwrap_or_default(),
        _ => "",
    }
}

fn alpn_of(stream: &Value) -> String {
    stream
        .pointer("/tlsSettings/alpn")
        .or_else(|| stream.pointer("/realitySettings/alpn"))
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(",")
        })
        .unwrap_or_default()
}

fn push_transport(
    params: &mut Vec<(&'static str, String)>,
    network: &str,
    host: &str,
    path: &str,
    header_type: &str,
) {
    match network {
        "ws" | "http" | "h2" | "xhttp" => {
            if !path.is_empty() {
                params.push(("path", path.to_string()));
            }
            if !host.is_empty() {
                params.push(("host", host.to_string()));
            }
        }
        "grpc" => {
            if !path.is_empty() {
                params.push(("serviceName", path.to_string()));
            }
        }
        "tcp" if header_type == "http" => {
            params.push(("headerType", "http".to_string()));
            if !path.is_empty() {
                params.push(("path", path.to_string()));
            }
            if !host.is_empty() {
                params.push(("host", host.to_string()));
            }
        }
        _ => {}
    }
}

fn push_tls(params: &mut Vec<(&'static str, String)>, sni: &str, fingerprint: &str, alpn: &str) {
    if !sni.is_empty() {
        params.push(("sni", sni.to_string()));
    }
    if !fingerprint.is_empty() {
        params.push(("fp", fingerprint.to_string()));
    }
    if !alpn.is_empty() {
        params.push(("alpn", alpn.to_string()));
    }
}

fn push_reality(stream: &Value, params: &mut Vec<(&'static str, String)>) {
    for (param, pointer) in [
        ("pbk", "/realitySettings/publicKey"),
        ("sid", "/realitySettings/shortId"),
        ("spx", "/realitySettings/spiderX"),
    ] {
        if let Some(value) = stream.pointer(pointer).and_then(Value::as_str) {
            if !value.is_empty() {
                params.push((param, value.to_string()));
            }
        }
    }
}

fn query(params: &[(&str, String)]) -> String {
    params
        .iter()
        .filter(|(_, value)| !value.is_empty())
        .map(|(key, value)| format!("{}={}", encode(key), encode(value)))
        .collect::<Vec<_>>()
        .join("&")
}

fn authority(address: &str, port: i64) -> String {
    let host = address.trim();
    if host.starts_with('[') || !host.contains(':') {
        format!("{host}:{port}")
    } else {
        format!("[{host}]:{port}")
    }
}

fn encode(input: &str) -> String {
    let mut out = String::with_capacity(input.len());
    for byte in input.bytes() {
        match byte {
            b'A'..=b'Z' | b'a'..=b'z' | b'0'..=b'9' | b'-' | b'_' | b'.' | b'~' => {
                out.push(byte as char)
            }
            _ => out.push_str(&format!("%{byte:02X}")),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    use sqlx::types::Json;

    fn inbound(protocol: &str, settings: Value, stream: Value) -> Inbound {
        Inbound {
            id: 1,
            user_id: 1,
            up: 0,
            down: 0,
            last_up: 0,
            last_down: 0,
            total: 0,
            remark: "节点".into(),
            sub_sort_index: 1,
            exclude_from_sub: false,
            enable: true,
            expiry_time: 0,
            traffic_reset: "never".into(),
            traffic_reset_day: 1,
            last_traffic_reset_time: 0,
            listen: String::new(),
            port: 443,
            protocol: protocol.into(),
            settings: Json(settings),
            stream_settings: Json(stream),
            sniffing: Json(json!({})),
            tag: "in-1".into(),
            share_addr_strategy: "node".into(),
            share_addr: String::new(),
            disable_flow: false,
            created_at: 0,
            updated_at: 0,
        }
    }

    fn client(settings: Value) -> Client {
        Client {
            id: 1,
            inbound_id: 1,
            email: "u1".into(),
            enable: true,
            up: 0,
            down: 0,
            last_up: 0,
            last_down: 0,
            total: 0,
            expiry_time: 0,
            settings: Json(settings),
            comment: String::new(),
            group_name: String::new(),
            limit_ip: 0,
            limit_hwid: 0,
            reset_days: 0,
            last_reset_time: 0,
            last_online: 0,
            inbound_ids: vec![1],
            created_at: 0,
            updated_at: 0,
        }
    }

    #[test]
    fn vless_reality_link_has_reality_params() {
        let inbound = inbound(
            "vless",
            json!({"decryption":"none"}),
            json!({
                "network": "tcp",
                "security": "reality",
                "realitySettings": {
                    "serverName": "example.com",
                    "publicKey": "PUB",
                    "shortId": "abcd",
                    "spiderX": "/",
                    "settings": {"fingerprint": "chrome"}
                }
            }),
        );
        let link = client_link(
            &inbound,
            &client(json!({"id":"11111111-1111-1111-1111-111111111111"})),
            "203.0.113.1",
        )
        .unwrap()
        .unwrap();
        assert!(link.starts_with("vless://11111111-1111-1111-1111-111111111111@203.0.113.1:443?"));
        assert!(link.contains("security=reality"));
        assert!(link.contains("pbk=PUB"));
        assert!(link.contains("sid=abcd"));
        assert!(link.contains("sni=example.com"));
        assert!(link.ends_with("#%E8%8A%82%E7%82%B9-u1"));
    }

    #[test]
    fn vless_encrypted_link_carries_client_encryption() {
        let inbound = inbound(
            "vless",
            json!({
                "decryption": "mlkem768x25519plus.native.600s.SERVERKEY",
                "encryption": "mlkem768x25519plus.native.0rtt.CLIENTKEY"
            }),
            json!({"network": "tcp"}),
        );
        let link = client_link(
            &inbound,
            &client(json!({"id":"11111111-1111-1111-1111-111111111111"})),
            "203.0.113.1",
        )
        .unwrap()
        .unwrap();
        assert!(link.contains("encryption=mlkem768x25519plus.native.0rtt.CLIENTKEY"));
        assert!(!link.contains("SERVERKEY"));
    }

    #[test]
    fn plain_vless_link_keeps_encryption_none() {
        let inbound = inbound(
            "vless",
            json!({"decryption": "none"}),
            json!({"network": "tcp"}),
        );
        let link = client_link(
            &inbound,
            &client(json!({"id":"11111111-1111-1111-1111-111111111111"})),
            "203.0.113.1",
        )
        .unwrap()
        .unwrap();
        assert!(link.contains("encryption=none"));
    }

    #[test]
    fn vmess_link_decodes_to_expected_json() {
        let inbound = inbound("vmess", json!({}), json!({"network":"ws","security":"tls"}));
        let link = client_link(
            &inbound,
            &client(json!({"id":"22222222-2222-2222-2222-222222222222"})),
            "203.0.113.2",
        )
        .unwrap()
        .unwrap();
        let payload = link.strip_prefix("vmess://").unwrap();
        let decoded = STANDARD.decode(payload).unwrap();
        let value: Value = serde_json::from_slice(&decoded).unwrap();
        assert_eq!(value["add"], "203.0.113.2");
        assert_eq!(value["port"], "443");
        assert_eq!(value["net"], "ws");
        assert_eq!(value["tls"], "tls");
    }

    #[test]
    fn shadowsocks_link_uses_sip002_userinfo() {
        let inbound = inbound(
            "shadowsocks",
            json!({"method":"2022-blake3-aes-128-gcm"}),
            json!({"network":"tcp"}),
        );
        let link = client_link(
            &inbound,
            &client(json!({"password":"cGFzc3dvcmQ="})),
            "203.0.113.3",
        )
        .unwrap()
        .unwrap();
        assert!(link.starts_with("ss://"));
        let userinfo = link
            .strip_prefix("ss://")
            .unwrap()
            .split('@')
            .next()
            .unwrap();
        let decoded = URL_SAFE_NO_PAD.decode(userinfo).unwrap();
        assert_eq!(
            String::from_utf8(decoded).unwrap(),
            "2022-blake3-aes-128-gcm:cGFzc3dvcmQ="
        );
    }
}
